  ISO 3166-1 country names and an IANA time-zone to country map.

  Both tables are generated from the system tz database (`iso3166.tab` and
  `zone.tab`), which is the same source browsers and operating systems agree on.
  They are compiled in as literal maps so lookups are constant-time and need no
  process, file or dependency.

  A handful of country names are overridden where the tz database's spelling
  reads oddly on a chart — "Britain (UK)" becomes "United Kingdom", "Korea
  (South)" becomes "South Korea", and so on. Everything else is used verbatim.

  The time-zone table exists only as a last-resort fallback: a browser always
  reports its zone, so a country can be guessed even with no GeoIP database and
  no CDN headers. It is a guess about *country* and nothing finer — a zone name
  like `America/Los_Angeles` names the zone's reference city, not the visitor's,
  so it is never used to infer a city.
  """

