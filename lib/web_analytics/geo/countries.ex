  @doc "Country name for an ISO 3166-1 alpha-2 code, or nil."
  def name(nil), do: nil

  def name(code) when is_binary(code) do
    Map.get(@countries, String.upcase(code))
  end

  def name(_), do: nil

  @doc "Whether a string is a country code this module knows."
  def known?(code) when is_binary(code), do: Map.has_key?(@countries, String.upcase(code))
  def known?(_), do: false

