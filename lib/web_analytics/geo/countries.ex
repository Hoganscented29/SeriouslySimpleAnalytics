  @doc """
  ISO code for a country name, or nil.

  Callers of the ping API send whatever their own data holds — "United States",
  "USA", "us" — so the name is matched case-insensitively and a two-letter value
  is treated as a code.
  """
  def code_for(nil), do: nil

  def code_for(value) when is_binary(value) do
    trimmed = String.trim(value)
    upcased = String.upcase(trimmed)

    cond do
      Map.has_key?(@countries, upcased) -> upcased
      true -> lookup_by_name(String.downcase(trimmed))
    end
  end

  def code_for(_), do: nil

  @by_name Map.new(@countries, fn {code, name} -> {String.downcase(name), code} end)

